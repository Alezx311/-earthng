def build(out, lang='uk'):
    out.mkdir(parents=True, exist_ok=True)
    path = out / ZIP
    with zipfile.ZipFile(path, 'w', zipfile.ZIP_DEFLATED) as z:
        for src in sorted(MOD.rglob('*')):
            if not src.is_file():
                continue
            name = src.relative_to(MOD).as_posix()
            if name == WORLD_LUA:
                text = src.read_text(encoding='utf8')
                line = "local LANG = 'uk'"
                if text.count(line) != 1:
                    raise SystemExit(f'{WORLD_LUA}: no single "{line}" line to set the language')
                z.writestr(name, text.replace(line, f"local LANG = '{lang}'"))
            else:
                z.write(src, name)
        for name, data in level_files(lang).items():
            z.writestr(name, data)
    return path


def main():
    p = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    p.add_argument('--out', type=Path, required=True)
    p.add_argument('--install', type=Path, help='BeamNG user folder (…/BeamNG.drive/current)')
    p.add_argument('--lang', choices=sorted(INFO), default='uk')
    a = p.parse_args()
    path = build(a.out, a.lang)
    print(path)
    if a.install:
        mods = a.install / 'mods'
        mods.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, mods / ZIP)
        print('installed', mods / ZIP)


if __name__ == '__main__':
    main()
